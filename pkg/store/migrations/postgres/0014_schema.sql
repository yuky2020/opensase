-- PostgreSQL schema (ADR-0033), equal to the SQLite schema after migrations 0001-0014.
-- Later changes add a file with the same name to migrations/ (SQLite) and to this
-- directory. Types: INTEGER -> BIGINT, BLOB -> BYTEA, AUTOINCREMENT -> identity.
CREATE TABLE tenants (
    id         TEXT PRIMARY KEY,
    name       TEXT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE TABLE users (
    id         TEXT PRIMARY KEY,
    tenant_id  TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    email      TEXT NOT NULL,
    name       TEXT NOT NULL,
    created_at BIGINT NOT NULL,
    UNIQUE (tenant_id, email)
);

CREATE TABLE devices (
    id          TEXT PRIMARY KEY,
    tenant_id   TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    user_id     TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    platform    TEXT NOT NULL,
    cert_serial TEXT NOT NULL,
    revoked     BIGINT NOT NULL DEFAULT 0,
    created_at  BIGINT NOT NULL
);
CREATE INDEX devices_tenant ON devices(tenant_id, user_id);

CREATE TABLE provisioning_keys (
    key_hash   BYTEA PRIMARY KEY,
    tenant_id  TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    user_id    TEXT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    max_uses   BIGINT NOT NULL,
    uses       BIGINT NOT NULL DEFAULT 0,
    expires_at BIGINT NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE TABLE tenant_policy (
    tenant_id  TEXT PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
    policy     TEXT NOT NULL, -- JSON api.TenantPolicy
    updated_at BIGINT NOT NULL
);

CREATE TABLE user_rules (
    user_id    TEXT PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    tenant_id  TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    rules      TEXT NOT NULL, -- JSON api.UserRules
    updated_at BIGINT NOT NULL
);

CREATE TABLE snapshot_versions (
    version    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id  TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    envelope   BYTEA,           -- JSON policy.Envelope
    issued_at  BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX snapshot_versions_device ON snapshot_versions(device_id, version);

CREATE TABLE flows (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    device_id TEXT NOT NULL,
    where_    TEXT NOT NULL,
    start     BIGINT NOT NULL,
    record    TEXT NOT NULL -- JSON api.FlowRecord
);
CREATE INDEX flows_tenant ON flows(tenant_id, id);
CREATE TABLE edges (
    id         TEXT PRIMARY KEY,
    revoked    BIGINT NOT NULL DEFAULT 0,
    created_at BIGINT NOT NULL
);

CREATE TABLE edge_sessions (
    edge_id    TEXT NOT NULL REFERENCES edges(id) ON DELETE CASCADE,
    device_id  TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (edge_id, device_id)
);

CREATE INDEX flows_start ON flows(start);

ALTER TABLE devices ADD COLUMN prev_cert_serial TEXT NOT NULL DEFAULT '';
CREATE TABLE connectors (
    id               TEXT PRIMARY KEY,
    rowid            BIGINT GENERATED BY DEFAULT AS IDENTITY, -- insertion order, as SQLite's rowid
    tenant_id        TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    name             TEXT NOT NULL,
    grp              TEXT NOT NULL,
    cert_serial      TEXT NOT NULL DEFAULT '',
    prev_cert_serial TEXT NOT NULL DEFAULT '',
    revoked          BIGINT NOT NULL DEFAULT 0,
    created_at       BIGINT NOT NULL,
    last_seen        BIGINT NOT NULL DEFAULT 0, -- last Edge report of a live broker connection
    -- ConnectorConfig versioning: the version increases whenever the served config changes
    -- (config_hash covers the tenant policy version, the edges and the group's apps).
    config_version   BIGINT NOT NULL DEFAULT 0,
    config_hash      BYTEA
);
CREATE INDEX connectors_tenant ON connectors(tenant_id, created_at);

CREATE TABLE connector_provisioning_keys (
    key_hash     BYTEA PRIMARY KEY,
    tenant_id    TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    connector_id TEXT NOT NULL REFERENCES connectors(id) ON DELETE CASCADE,
    used         BIGINT NOT NULL DEFAULT 0,
    expires_at   BIGINT NOT NULL,
    created_at   BIGINT NOT NULL
);
CREATE INDEX connector_provisioning_keys_connector ON connector_provisioning_keys(connector_id);

ALTER TABLE tenant_policy ADD COLUMN version BIGINT NOT NULL DEFAULT 0;
ALTER TABLE edges ADD COLUMN tenant_id TEXT REFERENCES tenants(id) ON DELETE CASCADE;
CREATE TABLE admin_tokens (
    id          TEXT PRIMARY KEY,
    tenant_id   TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    name        TEXT NOT NULL,
    token_hash  BYTEA NOT NULL UNIQUE,
    created_at  BIGINT NOT NULL,
    expires_at  BIGINT NOT NULL,
    revoked     BIGINT NOT NULL DEFAULT 0,
    last_used   BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX admin_tokens_tenant ON admin_tokens(tenant_id, created_at);
CREATE TABLE admin_audit (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at         BIGINT NOT NULL,
    actor      TEXT NOT NULL,
    tenant_id  TEXT NOT NULL DEFAULT '',
    method     TEXT NOT NULL,
    path       TEXT NOT NULL,
    status     BIGINT NOT NULL
);
CREATE INDEX admin_audit_tenant ON admin_audit(tenant_id, id);
CREATE INDEX admin_audit_at ON admin_audit(at);
ALTER TABLE admin_tokens ADD COLUMN role TEXT NOT NULL DEFAULT 'admin';
ALTER TABLE admin_audit ADD COLUMN prev_hash BYTEA;
ALTER TABLE admin_audit ADD COLUMN hash BYTEA;
CREATE TABLE audit_anchor (
    id      BIGINT PRIMARY KEY CHECK (id = 1),
    last_id BIGINT NOT NULL,
    hash    BYTEA NOT NULL
);
CREATE TABLE dlp_datasets (
    tenant_id  TEXT NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    name       TEXT NOT NULL,
    kind       TEXT NOT NULL,
    hkey       BYTEA NOT NULL,
    hashes     BYTEA NOT NULL,
    count      BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, name)
);
CREATE TABLE tenant_oidc (
    tenant_id     TEXT PRIMARY KEY REFERENCES tenants(id) ON DELETE CASCADE,
    issuer        TEXT NOT NULL,
    client_id     TEXT NOT NULL,
    client_secret TEXT NOT NULL DEFAULT '',
    group_roles   TEXT NOT NULL, -- JSON object group -> role
    updated_at    BIGINT NOT NULL
);
CREATE TABLE device_routes (
    device_id TEXT NOT NULL REFERENCES devices(id) ON DELETE CASCADE,
    tenant_id TEXT NOT NULL,
    cidr      TEXT NOT NULL,
    PRIMARY KEY (device_id, cidr)
);
CREATE INDEX device_routes_tenant ON device_routes(tenant_id, device_id);
CREATE TABLE oidc_pending (
    state      TEXT PRIMARY KEY,
    tenant_id  TEXT NOT NULL,
    verifier   TEXT NOT NULL,
    nonce      TEXT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX oidc_pending_expires ON oidc_pending(expires_at);
CREATE UNIQUE INDEX admin_audit_prev_hash ON admin_audit(prev_hash) WHERE prev_hash IS NOT NULL;
CREATE TABLE cas (
    tenant_id  TEXT NOT NULL,
    kind       TEXT NOT NULL,
    cert_pem   BYTEA NOT NULL,
    sealed_key BYTEA NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (tenant_id, kind)
);
